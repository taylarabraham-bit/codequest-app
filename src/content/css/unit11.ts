// A short list, so position selectors have several items to pick from.
const list = (items: string[], tag = 'ul') => `<${tag}>${items.map((i) => `<li>${i}</li>`).join('')}</${tag}>`;
// A checkbox (or radio) with its label right after it, for :checked + label.
const tick = (id: string, text: string, checked = false, type = 'checkbox', name = '') =>
  `<div><input type="${type}" id="${id}"${name ? ` name="${name}"` : ''}${checked ? ' checked' : ''}><label for="${id}"> ${text}</label></div>`;

