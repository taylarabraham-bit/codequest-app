// Shorthand parts like `spin 1s linear` may come in any order, so every order is valid.
const perms = (xs: string[]): string[][] =>
  xs.length <= 1 ? [xs] : xs.flatMap((x, i) => perms([...xs.slice(0, i), ...xs.slice(i + 1)]).map((p) => [x, ...p]));

const fanOrders = perms(['spin', '1s', 'linear']).map((p) => ['.fan', '{', 'animation:', ...p, 'infinite;', '}']);

const pulseAccept = perms(['pulse', '1s', 'infinite', 'alternate']).flatMap((p) => [
  `animation: ${p.join(' ')};`,
  `animation: ${p.join(' ')}`,
]);

