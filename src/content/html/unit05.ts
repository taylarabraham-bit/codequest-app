const perms = (xs: string[]): string[][] =>
  xs.length <= 1 ? [xs] : xs.flatMap((x, i) => perms([...xs.slice(0, i), ...xs.slice(i + 1)]).map((p) => [x, ...p]));

/** Every other order of a tag's attributes, as token lists (for build `alt`). */
function attrOrders(open: string, attrs: string[], rest: string[]): string[][] {
  return perms(attrs)
    .slice(1)
    .map((p) => [open, ...p, ...rest]);
}

/** Every order of the attributes, each in any listed spelling. The first spelling,
 * in the given order, comes first (canonical). */
function attrSets(attrs: string[][]): string[] {
  const combos = attrs.reduce<string[][]>((acc, alts) => acc.flatMap((a) => alts.map((s) => [...a, s])), [[]]);
  return combos.flatMap((c) => perms(c).map((p) => p.join(' ')));
}

/** Accepted ways to type an empty tag: any attribute order and spelling, closed
 * with > (or />, only with quoted values: `name=x/>` would make the value "x/"). */
function emptyTag(name: string, attrs: string[][]): string[] {
  return [
    ...attrSets(attrs).map((a) => `<${name} ${a}>`),
    ...attrSets(attrs.map((a) => [a[0]])).map((a) => `<${name} ${a}/>`),
  ];
}

